    let activeMedia = 0;
    let activeProject = null;

    function mediaKind(item) {
      const t = i18n[currentLang] || i18n.en;
      return item.type === 'video' ? t.overlay_video : t.overlay_foto;
    }

    function renderStage(project, index) {
      const item = project.media[index];
      if (!item) return;
      const stage = mediaEl.querySelector('.project-stage');
      if (!stage) return;
      if (item.type === 'video') {
        stage.innerHTML = '<video controls playsinline muted preload="metadata" src="' + item.src + '" aria-label="' + (item.alt || '') + '"></video>';
      } else {
        stage.innerHTML = '<img src="' + item.src + '" alt="' + (item.alt || '') + '">';
      }
      if (!project.kind) kindEl.textContent = mediaKind(item);
      mediaEl.querySelectorAll('.project-thumb-btn').forEach((btn, i) => {
        btn.classList.toggle('active', i === index);
      });
      activeMedia = index;
    }

    function openProject(id) {
      const project = PROJECTS[id];
      if (!project) return;
      activeProject = id;
      const t = i18n[currentLang] || i18n.en;
      const kindKey = project.kind === 'research' ? 'kind_research' : project.kind === 'product' ? 'kind_product' : '';
      kindEl.textContent = kindKey ? (t[kindKey] || '') : '';
      titleEl.textContent = project.title;
      const desc = project.desc[currentLang] || project.desc.en;
      if (/<[a-z][\s\S]*>/i.test(desc)) descEl.innerHTML = desc;
      else descEl.textContent = desc;
      closeBtn.setAttribute('aria-label', t.overlay_close);
      const linksEl = document.getElementById('projectDetailLinks');
      const kindLabel = { repo: t.link_repo, paper: t.link_paper, pdf: t.link_pdf, live: t.link_live };
      linksEl.innerHTML = (project.links || []).map(function(l) {
        const label = kindLabel[l.kind] || t.overlay_link;
        return '<a class="link-arrow" href="' + l.href + '" target="_blank" rel="noopener noreferrer">' + label + '<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><line x1="7" y1="17" x2="17" y2="7"/><polyline points="7 7 17 7 17 17"/></svg></a>';
      }).join('');

      if (!project.media.length) {
        mediaEl.classList.add('is-empty');
        mediaEl.innerHTML = '';
        kindEl.textContent = '';
      } else {
        mediaEl.classList.remove('is-empty');
        const thumbs = project.media.length > 1
          ? '<div class="project-thumbs">' + project.media.map((m, i) => {
              const inner = m.type === 'video'
                ? '<video src="' + m.src + '" muted></video>'
                : '<img src="' + m.src + '" alt="">';
              return '<button type="button" class="project-thumb-btn' + (i===0?' active':'') + '" data-i="' + i + '" aria-label="' + (m.alt || '') + '">' + inner + '</button>';
            }).join('') + '</div>'
          : '<div class="project-thumbs" hidden></div>';
        const role = project.role ? (project.role[currentLang] || project.role.en) : '';
        const roleHtml = role ? '<p class="project-role">' + role + '</p>' : '';
        mediaEl.innerHTML = '<div class="project-stage"></div>' + thumbs + roleHtml;
        renderStage(project, 0);
        mediaEl.querySelectorAll('.project-thumb-btn').forEach(btn => {
          btn.addEventListener('click', () => renderStage(project, Number(btn.dataset.i)));
        });
      }

      overlay.hidden = false;
      document.body.classList.add('overlay-open');
      closeBtn.focus();
      if (location.hash !== '#project-' + id) history.replaceState(null, '', '#project-' + id);
    }

    function closeProject() {
      overlay.hidden = true;
      document.body.classList.remove('overlay-open');
      mediaEl.querySelectorAll('video').forEach(v => { v.pause(); });
      activeProject = null;
      if (location.hash.startsWith('#project-')) history.replaceState(null, '', location.pathname + location.search);
    }

